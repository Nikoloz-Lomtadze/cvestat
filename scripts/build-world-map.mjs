// Generates src/components/radar/world.ts: a pixel-dot world map + one point per country.
// Run once with:  node scripts/build-world-map.mjs
// Map data: Natural Earth via the world-atlas package (public domain).
import { readFileSync, writeFileSync } from "node:fs";
import { geoArea, geoCentroid, geoContains, geoEquirectangular } from "d3-geo";
import { feature } from "topojson-client";
import countries from "i18n-iso-countries";

const COLS = 180; // map width in "pixels"
const ROWS = 76; // latitude 84°N .. 58°S (Antarctica cut off)
const LAT_TOP = 84;
const LAT_BOTTOM = -58;

const load = (f) => JSON.parse(readFileSync(new URL(`../node_modules/world-atlas/${f}`, import.meta.url)));

// Equirectangular projection scaled so the map is exactly COLS × ROWS units.
const proj = geoEquirectangular()
  .scale(COLS / (2 * Math.PI))
  .translate([COLS / 2, 0])
  .center([0, LAT_TOP]);
const k = ROWS / proj([0, LAT_BOTTOM])[1]; // squeeze vertically to fit ROWS
const project = ([lon, lat]) => {
  const [x, y] = proj([lon, lat]);
  return [Math.round(x * 10) / 10, Math.round(y * k * 10) / 10];
};

// ---- land dots ----
const land = feature(load("land-110m.json"), load("land-110m.json").objects.land);
const rows = [];
for (let r = 0; r < ROWS; r++) {
  let row = "";
  for (let c = 0; c < COLS; c++) {
    const lon = -180 + ((c + 0.5) / COLS) * 360;
    const lat = LAT_TOP - ((r + 0.5) / ROWS) * (LAT_TOP - LAT_BOTTOM);
    row += geoContains(land, [lon, lat]) ? "#" : ".";
  }
  rows.push(row);
}

// ---- country points (centre of the biggest piece, so France isn't placed in the ocean) ----
const topo = load("countries-50m.json");
const points = {};
for (const f of feature(topo, topo.objects.countries).features) {
  const a2 = f.id && countries.numericToAlpha2(f.id);
  if (!a2) continue;
  let geom = f;
  if (f.geometry.type === "MultiPolygon") {
    const biggest = f.geometry.coordinates
      .map((coordinates) => ({ type: "Polygon", coordinates }))
      .sort((a, b) => geoArea(b) - geoArea(a))[0];
    geom = biggest;
  }
  points[a2] = project(geoCentroid(geom));
}
// Places Radar can return that the atlas doesn't give an ISO code for.
const extra = { XK: [21, 42.6], HK: [114.17, 22.32], SG: [103.82, 1.35], MO: [113.55, 22.2], TW: [121, 23.7], BH: [50.55, 26.07], MT: [14.4, 35.9] };
for (const [a2, lonLat] of Object.entries(extra)) points[a2] ??= project(lonLat);
// Mainland US / Norway etc. look better slightly adjusted
points.US = project([-98.5, 39.5]);
points.NO = project([9, 61]);
points.RU = project([60, 57]);
points.CA = project([-100, 56]);

const out = `// GENERATED by scripts/build-world-map.mjs — do not edit by hand.
// Map data: Natural Earth (public domain) via world-atlas.
export const MAP_W = ${COLS};
export const MAP_H = ${ROWS};
/** One string per row; "#" = land dot. */
export const LAND: string[] = ${JSON.stringify(rows, null, 0).replace(/","/g, '",\n  "')};
/** Country code → [x, y] on the map. */
export const POINTS: Record<string, [number, number]> = ${JSON.stringify(points)};
`;
writeFileSync(new URL("../src/components/radar/world.ts", import.meta.url), out);
console.log("countries:", Object.keys(points).length, "land dots:", rows.join("").split("#").length - 1);
